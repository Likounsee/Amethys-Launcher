#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum DistributionMode {
    /// Amethys may download/install only when the provider explicitly authorizes it.
    AmethysManaged,
    /// The official provider client/API remains responsible for installation and licences.
    OfficialPlatformManaged,
    /// The offer is a link to an external official page.
    ExternalLink,
    /// Metadata only; no action is promised.
    MetadataOnly,
}

