/// Identity and display information for one catalogue feed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CatalogSourceDescriptor {
    pub id: String,
    pub display_name: String,
    pub kind: String,
}

/// Implemented by file, embedded or (later) network-backed catalogue sources.
pub trait CatalogSourceAdapter: Send + Sync {
    fn descriptor(&self) -> CatalogSourceDescriptor;
    fn load_document(&self) -> CatalogResult<Vec<u8>>;
}

/// Reads a bounded local JSON catalogue. Network transport is intentionally
/// left to a later lot; this adapter is useful for bundled and user-managed feeds.
#[derive(Debug, Clone)]
pub struct StaticJsonCatalogSource {
    descriptor: CatalogSourceDescriptor,
    path: PathBuf,
    max_bytes: usize,
}

impl StaticJsonCatalogSource {
    pub fn new(
        id: impl Into<String>,
        display_name: impl Into<String>,
        path: impl Into<PathBuf>,
    ) -> CatalogResult<Self> {
        let id = id.into();
        let display_name = display_name.into();
        validate_identifier(&id, "catalogue source ID")?;
        validate_text(&display_name, 256, "catalogue source name")?;
        Ok(Self {
            descriptor: CatalogSourceDescriptor {
                id,
                display_name,
                kind: "static_json".into(),
            },
            path: path.into(),
            max_bytes: MAX_CATALOG_BYTES,
        })
    }

    pub fn with_max_bytes(mut self, max_bytes: usize) -> CatalogResult<Self> {
        if max_bytes == 0 || max_bytes > MAX_CATALOG_BYTES {
            return Err(CatalogError::Source(format!(
                "source size limit must be between 1 and {MAX_CATALOG_BYTES} bytes"
            )));
        }
        self.max_bytes = max_bytes;
        Ok(self)
    }

    pub fn path(&self) -> &Path {
        &self.path
    }
}

impl CatalogSourceAdapter for StaticJsonCatalogSource {
    fn descriptor(&self) -> CatalogSourceDescriptor {
        self.descriptor.clone()
    }

    fn load_document(&self) -> CatalogResult<Vec<u8>> {
        let metadata = fs::symlink_metadata(&self.path)
            .map_err(|error| CatalogError::Source(format!("cannot inspect source file: {error}")))?;
        if metadata.file_type().is_symlink() || !metadata.is_file() {
            return Err(CatalogError::Source(
                "catalogue source must be a regular file, not a symlink".into(),
            ));
        }
        if metadata.len() > self.max_bytes as u64 {
            return Err(CatalogError::Source(format!(
                "catalogue source exceeds the {}-byte limit",
                self.max_bytes
            )));
        }
        let file = fs::File::open(&self.path)
            .map_err(|error| CatalogError::Source(format!("cannot open source file: {error}")))?;
        let mut bytes = Vec::with_capacity(metadata.len() as usize);
        file.take(self.max_bytes as u64 + 1)
            .read_to_end(&mut bytes)
            .map_err(|error| CatalogError::Source(format!("cannot read source file: {error}")))?;
        if bytes.len() > self.max_bytes {
            return Err(CatalogError::Source(format!(
                "catalogue source exceeds the {}-byte limit",
                self.max_bytes
            )));
        }
        Ok(bytes)
    }
}

/// Validates the complete document before any cache mutation is attempted.
pub fn parse_and_validate(
    bytes: &[u8],
    providers: &ProviderRegistry,
) -> CatalogResult<CatalogDocument> {
    if bytes.is_empty() || bytes.len() > MAX_CATALOG_BYTES {
        return Err(CatalogError::InvalidDocument(format!(
            "document size must be between 1 and {MAX_CATALOG_BYTES} bytes"
        )));
    }
    let document: CatalogDocument = serde_json::from_slice(bytes)
        .map_err(|error| CatalogError::InvalidDocument(format!("invalid JSON/schema: {error}")))?;
    validate_document(&document, providers)?;
    Ok(document)
}

pub fn validate_document(
    document: &CatalogDocument,
    providers: &ProviderRegistry,
) -> CatalogResult<()> {
    if document.schema_version != CATALOG_SCHEMA_VERSION {
        return Err(CatalogError::InvalidDocument(format!(
            "unsupported schema version {}; expected {}",
            document.schema_version, CATALOG_SCHEMA_VERSION
        )));
    }
    validate_identifier(&document.catalog_id, "catalogue ID")?;
    if document.catalog_version == 0 {
        return Err(CatalogError::InvalidDocument(
            "catalogue version must be greater than zero".into(),
        ));
    }
    validate_text(&document.generated_at, 64, "generation timestamp")?;
    if document.games.len() > MAX_GAMES_PER_CATALOG {
        return Err(CatalogError::InvalidDocument("too many games".into()));
    }

    let mut game_ids = BTreeSet::new();
    let mut offer_ids = BTreeSet::new();
    let mut provider_external_ids = BTreeSet::new();
    let mut offer_count = 0usize;

    for game in &document.games {
        validate_identifier(&game.id, "game ID")?;
        if !game_ids.insert(&game.id) {
            return Err(CatalogError::InvalidDocument(format!(
                "duplicate game ID '{}'",
                game.id
            )));
        }
        validate_text(&game.title, MAX_TITLE_BYTES, "game title")?;
        validate_optional_text(&game.description, MAX_DESCRIPTION_BYTES, "description")?;
        validate_optional_text(&game.developer, 512, "developer")?;
        validate_optional_text(&game.publisher, 512, "publisher")?;
        validate_optional_text(&game.release_date, 32, "release date")?;
        validate_optional_text(&game.cover_ref, 2048, "cover reference")?;
        validate_optional_text(&game.banner_ref, 2048, "banner reference")?;
        if game.genres.len() > 64 {
            return Err(CatalogError::InvalidDocument("a game has more than 64 genres".into()));
        }
        for genre in &game.genres {
            validate_text(genre, 128, "genre")?;
        }

        offer_count = offer_count.saturating_add(game.offers.len());
        if offer_count > MAX_OFFERS_PER_CATALOG {
            return Err(CatalogError::InvalidDocument("too many offers".into()));
        }
        for offer in &game.offers {
            validate_identifier(&offer.id, "offer ID")?;
            validate_identifier(&offer.provider_id, "provider ID")?;
            validate_text(&offer.external_id, 512, "external offer ID")?;
            validate_optional_text(&offer.title, MAX_TITLE_BYTES, "offer title")?;
            if !offer_ids.insert(offer.id.clone()) {
                return Err(CatalogError::InvalidDocument(format!(
                    "duplicate offer ID '{}'",
                    offer.id
                )));
            }
            if !provider_external_ids.insert((offer.provider_id.clone(), offer.external_id.clone())) {
                return Err(CatalogError::InvalidDocument(format!(
                    "duplicate external identity '{}' for provider '{}'",
                    offer.external_id, offer.provider_id
                )));
            }
            let provider = providers.get(&offer.provider_id).ok_or_else(|| {
                CatalogError::Provider(format!("unknown provider '{}'", offer.provider_id))
            })?;
            validate_offer(offer, &provider.capabilities)?;
        }
    }
    Ok(())
}

fn validate_offer(offer: &CatalogOffer, provider: &ProviderCapabilities) -> CatalogResult<()> {
    let requested = &offer.capabilities;
    if requested.official_launch && !provider.official_launch
        || requested.direct_install && !provider.direct_install
        || requested.update && !provider.update
        || requested.repair && !provider.repair
    {
        return Err(CatalogError::InvalidDocument(format!(
            "offer '{}' claims capabilities not declared by provider '{}'",
            offer.id, offer.provider_id
        )));
    }
    if (requested.update || requested.repair) && !requested.direct_install {
        return Err(CatalogError::InvalidDocument(format!(
            "offer '{}' enables update/repair without direct installation",
            offer.id
        )));
    }

    match offer.distribution {
        DistributionMode::AmethysManaged => {
            if !requested.direct_install || offer.manifest_reference.is_none() {
                return Err(CatalogError::InvalidDocument(format!(
                    "Amethys-managed offer '{}' requires authorized direct_install and a manifest reference",
                    offer.id
                )));
            }
            validate_https_reference(offer.manifest_reference.as_deref().unwrap(), "manifest reference")?;
            if offer.external_url.is_some() {
                return Err(CatalogError::InvalidDocument(format!(
                    "Amethys-managed offer '{}' must not also declare an external URL",
                    offer.id
                )));
            }
        }
        DistributionMode::OfficialPlatformManaged => {
            if !requested.official_launch || offer.external_url.is_none() {
                return Err(CatalogError::InvalidDocument(format!(
                    "official-platform offer '{}' requires official_launch and an official URL",
                    offer.id
                )));
            }
            if requested.direct_install || requested.update || requested.repair || offer.manifest_reference.is_some() {
                return Err(CatalogError::InvalidDocument(format!(
                    "official-platform offer '{}' cannot claim Amethys-managed file operations",
                    offer.id
                )));
            }
            validate_https_reference(offer.external_url.as_deref().unwrap(), "external URL")?;
        }
        DistributionMode::ExternalLink => {
            if offer.external_url.is_none()
                || requested.official_launch
                || requested.direct_install
                || requested.update
                || requested.repair
                || offer.manifest_reference.is_some()
            {
                return Err(CatalogError::InvalidDocument(format!(
                    "external-link offer '{}' must only provide an external URL",
                    offer.id
                )));
            }
            validate_https_reference(offer.external_url.as_deref().unwrap(), "external URL")?;
        }
        DistributionMode::MetadataOnly => {
            if requested.official_launch || requested.direct_install || requested.update
                || requested.repair || offer.external_url.is_some() || offer.manifest_reference.is_some()
            {
                return Err(CatalogError::InvalidDocument(format!(
                    "metadata-only offer '{}' cannot advertise executable actions",
                    offer.id
                )));
            }
        }
    }
    Ok(())
}

fn validate_https_reference(value: &str, label: &str) -> CatalogResult<()> {
    validate_text(value, 2048, label)?;
    let lower = value.to_ascii_lowercase();
    if !lower.starts_with("https://")
        || value[8..].is_empty()
        || value.chars().any(char::is_whitespace)
        || value.contains('@') && value.split('/').nth(2).is_some_and(|host| host.contains('@'))
    {
        return Err(CatalogError::InvalidDocument(format!(
            "{label} must be an absolute HTTPS URL without whitespace or credentials"
        )));
    }
    Ok(())
}

fn validate_identifier(value: &str, label: &str) -> CatalogResult<()> {
    if value.is_empty()
        || value.len() > 128
        || !value.bytes().all(|byte| {
            byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.' | b':')
        })
    {
        return Err(CatalogError::InvalidDocument(format!(
            "{label} is empty, too long or contains unsupported characters"
        )));
    }
    Ok(())
}

fn validate_text(value: &str, max_bytes: usize, label: &str) -> CatalogResult<()> {
    if value.trim().is_empty() || value.len() > max_bytes || value.contains('\0') {
        return Err(CatalogError::InvalidDocument(format!(
            "{label} is empty, contains NUL or exceeds {max_bytes} bytes"
        )));
    }
    Ok(())
}

fn validate_optional_text(
    value: &Option<String>,
    max_bytes: usize,
    label: &str,
) -> CatalogResult<()> {
    if let Some(value) = value {
        validate_text(value, max_bytes, label)?;
    }
    Ok(())
}

